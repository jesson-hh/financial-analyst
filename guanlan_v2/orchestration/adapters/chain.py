def build_phase9_registry(
    expected_phase8_digest: "DigestHex",
) -> "Phase2RuntimeRegistry":
    """Build + seal the cumulative Phase-9 registry, pinned to the Phase-8 base.

    (Return-type note: the brief writes ``-> SchemaRegistry``; the sealed cumulative
    registry every chain node from Phase 2 onward actually builds is the Phase-2
    :class:`~guanlan_v2.orchestration.runtime_contracts.Phase2RuntimeRegistry`, which is
    NOT a ``schema_registry.SchemaRegistry`` subclass — annotating ``SchemaRegistry``
    would be false. Bound to the real type, exactly like the ``get_ohlcv`` → ``ohlcv``
    method-id correction; recorded in the task report.)

    Verifies ``expected_phase8_digest`` against the actual sealed Phase-8 cumulative
    registry digest first — any other base digest is rejected *before any
    registration* — then registers the complete inherited cumulative set (Phase-1
    public + Phase-2 runtime facts + Phase-3 data + Phase-3 memory + Phase-4
    Evaluator-Optimizer + Phase-5 Bootstrap Lane 0 + Phase-6 shadow + Phase-7
    dynamic-planner + Phase-8 lane payloads) followed by :data:`PHASE9_PUBLIC_MODELS`
    into a *fresh*
    :class:`~guanlan_v2.orchestration.runtime_contracts.Phase2RuntimeRegistry` and
    seals it. No upstream registry is mutated; a fresh sealed instance is returned per
    call. Inherited JSON Schemas stay byte-identical to their Phase-<=8 goldens; there
    is no "latest" alias.
    """
    from guanlan_v2.orchestration import (
        bootstrap,
        lane_catalog as p8,
        phase7_registry as p7,
        shadow,
        trial,
    )
    from guanlan_v2.orchestration.data.schema_registry import (
        PHASE3_PUBLIC_MODELS as _DATA_PUBLIC,
    )
    from guanlan_v2.orchestration.memory.schema_registry import (
        PHASE3_MEMORY_PUBLIC_MODELS as _MEM_PUBLIC,
    )
    from guanlan_v2.orchestration.runtime_contracts import (
        Phase2RuntimeRegistry,
        phase2_public_models,
    )

    actual = p8.PHASE8_REGISTRY_DIGEST
    if expected_phase8_digest != actual:
        raise Phase9RegistryError(
            "build_phase9_registry requires the exact Phase-8 registry digest "
            f"{actual!r}; got {expected_phase8_digest!r}"
        )
    reg = Phase2RuntimeRegistry()
    for model in (
        tuple(phase2_public_models())
        + tuple(_DATA_PUBLIC)
        + tuple(_MEM_PUBLIC)
        + tuple(trial.PHASE4_PUBLIC_MODELS)
        + tuple(bootstrap.PHASE5_PUBLIC_MODELS)
        + tuple(shadow.PHASE6_PUBLIC_MODELS)
        + tuple(p7.PHASE7_PUBLIC_MODELS)
        + tuple(p8.PHASE8_PUBLIC_MODELS)
        + PHASE9_PUBLIC_MODELS
    ):
        reg.register(model)
    reg.seal()
    return reg


