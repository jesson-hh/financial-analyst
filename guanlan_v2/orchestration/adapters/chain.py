def serialize_source_descriptor(descriptor: DataSourceDescriptor) -> bytes:
    """Serialize a :class:`DataSourceDescriptor` to deterministic canonical material bytes.

    Mirrors ``data.catalog.serialize_prefetch_binding`` — a sorted-key, ASCII-safe
    canonical JSON dump so the "source-config" catalog material's bytes (and therefore
    its content digest) are stable and reviewable, and encode the descriptor's own
    ``descriptor_digest``.
    """
    return json.dumps(
        descriptor.model_dump(mode="json"),
        sort_keys=True,
        ensure_ascii=False,
        separators=(",", ":"),
    ).encode("utf-8")


def build_phase9_source_materials() -> tuple[
    DataSourceDescriptor, DataSourceDescriptor, tuple[ResolvedTextMaterial, ...]
]:
    """Build the two adapter :class:`DataSourceDescriptor`\\ s + their catalog materials.

    Resolves the existing Phase-3 data method specs, builds each adapter's trusted
    handler material, binds the descriptor behind the EXISTING method / capability ids
    (:func:`~guanlan_v2.orchestration.adapters.replay_data.build_pit_replay_descriptor`
    / :func:`~guanlan_v2.orchestration.adapters.live_data.build_online_live_descriptor`,
    each rejecting any minted id), and serializes the descriptor into a "source-config"
    guardrail material. Returns ``(replay_descriptor, live_descriptor, (four materials))``
    — two handler materials + two serialized-descriptor materials.
    """
    method_specs = phase3_data_surface().method_specs

    replay_handler_ref, replay_handler_mat = build_text_material(
        id=_PIT_REPLAY_HANDLER_ID, version="1", kind="handler",
        raw=_PIT_REPLAY_HANDLER_BYTES)
    online_handler_ref, online_handler_mat = build_text_material(
        id=_ONLINE_HANDLER_ID, version="1", kind="handler",
        raw=_ONLINE_HANDLER_BYTES)

    replay_desc = build_pit_replay_descriptor(
        method_specs=method_specs, handler_ref=replay_handler_ref)
    live_desc = build_online_live_descriptor(
        method_specs=method_specs, handler_ref=online_handler_ref)

    _replay_cfg_ref, replay_cfg_mat = build_text_material(
        id=_PIT_REPLAY_DESCRIPTOR_ID, version="1", kind="guardrail",
        raw=serialize_source_descriptor(replay_desc))
    _online_cfg_ref, online_cfg_mat = build_text_material(
        id=_ONLINE_DESCRIPTOR_ID, version="1", kind="guardrail",
        raw=serialize_source_descriptor(live_desc))

    return replay_desc, live_desc, (
        replay_handler_mat, replay_cfg_mat, online_handler_mat, online_cfg_mat,
    )


def _verify_source_descriptor(
    descriptor: DataSourceDescriptor,
    *,
    expected_mode: DataMode,
    expected_method_ids: frozenset[str],
    spec_by_ref: dict[tuple[str, str, str], DataMethodSpec],
    known_caps: set,
) -> None:
    """Reject any descriptor that mints a new method / capability id or a write method.

    * ``supported_modes`` must be exactly ``(expected_mode,)`` — the structural mode
      exclusion (a PIT_REPLAY read can never resolve the ONLINE source, and vice versa).
    * every ``method_ref`` must cross-resolve to an EXISTING Phase-3 data method spec
      whose ``read_only`` is ``True`` (no order/signal write capability); the bound set
      must equal ``expected_method_ids`` — no new ``DataMethodSpec`` id is minted.
    * every ``method_capability_ref`` must be one of the EXISTING Phase-3 data
      capabilities — no new capability id is minted.
    """
    if descriptor.supported_modes != (expected_mode,):
        raise CatalogError(
            f"source {descriptor.source_id!r} supported_modes "
            f"{descriptor.supported_modes} != the reviewed exclusive ({expected_mode},)"
        )
    bound_ids: set[str] = set()
    for mref in descriptor.method_refs:
        spec = spec_by_ref.get((mref.id, mref.version, mref.content_digest))
        if spec is None:
            raise CatalogError(
                f"source {descriptor.source_id!r} references a method "
                f"{mref.id}@{mref.version} that is not an existing Phase-3 data method "
                "spec (no new DataMethodSpec id may be minted)"
            )
        if not spec.read_only:
            raise CatalogError(
                f"source {descriptor.source_id!r} binds non-read method {mref.id!r} — "
                "the adapter sources register no order/signal write capability"
            )
        bound_ids.add(spec.method_id)
    if bound_ids != set(expected_method_ids):
        raise CatalogError(
            f"source {descriptor.source_id!r} binds method ids {sorted(bound_ids)} != "
            f"the reviewed existing set {sorted(expected_method_ids)}"
        )
    for cref in descriptor.method_capability_refs:
        if cref not in known_caps:
            raise CatalogError(
                f"source {descriptor.source_id!r} references capability "
                f"{cref.id}@{cref.version} that is not an existing Phase-3 data "
                "capability (no new capability id may be minted)"
            )


def _source_content_entries(
    descriptor: DataSourceDescriptor,
    handler_id: str,
    descriptor_id: str,
    materials_by_key: dict[tuple[str, str], ResolvedTextMaterial],
) -> tuple[ContentManifestEntry, ContentManifestEntry]:
    """Derive one source's (handler, source-config) manifest entries + verify materials.

    The descriptor's ``handler_ref`` must resolve to the handler material (kind
    ``handler``, digest match); the serialized-descriptor material (kind ``guardrail``)
    must encode this exact descriptor's bytes. Both become materials-without-worker
    content manifest entries stamped with the Phase-9 provenance identity.
    """
    handler_mat = materials_by_key.get((handler_id, "1"))
    if handler_mat is None or handler_mat.kind != "handler":
        raise CatalogError(
            f"source {descriptor.source_id!r} handler material {handler_id}@1 is "
            "missing or not a handler material"
        )
    if (descriptor.handler_ref.id, descriptor.handler_ref.version) != (handler_id, "1"):
        raise CatalogError(
            f"source {descriptor.source_id!r} handler_ref does not name {handler_id}@1"
        )
    if descriptor.handler_ref.content_digest != handler_mat.ref.content_digest:
        raise CatalogError(
            f"source {descriptor.source_id!r} handler_ref digest does not match its "
            "resolved handler material"
        )

    cfg_mat = materials_by_key.get((descriptor_id, "1"))
    if cfg_mat is None or cfg_mat.kind != "guardrail":
        raise CatalogError(
            f"source {descriptor.source_id!r} source-config material {descriptor_id}@1 "
            "is missing or not a guardrail material"
        )
    if cfg_mat.raw_utf8 != serialize_source_descriptor(descriptor):
        raise CatalogError(
            f"source {descriptor.source_id!r} source-config material does not encode "
            "the reviewed descriptor bytes"
        )

    handler_entry = ContentManifestEntry(
        ref=handler_mat.ref, kind="handler", name=handler_id,
        description=f"phase9 adapter source handler material: {handler_id}",
        source_identity=PHASE9_SOURCE_IDENTITY)
    cfg_entry = ContentManifestEntry(
        ref=cfg_mat.ref, kind="guardrail", name=descriptor_id,
        description=(
            f"phase9 adapter source-config (serialized DataSourceDescriptor "
            f"{descriptor.source_id}@{descriptor.source_version}, digest "
            f"{descriptor.descriptor_digest[:12]}…): {descriptor_id}"),
        source_identity=PHASE9_SOURCE_IDENTITY)
    return handler_entry, cfg_entry


def build_phase9_catalog_snapshot(
    phase8_snapshot: "WorkerCatalogSnapshot",
    *,
    replay_source_descriptor: DataSourceDescriptor,
    live_source_descriptor: DataSourceDescriptor,
    resolved_materials: tuple[ResolvedMaterial, ...],
) -> "WorkerCatalogSnapshot":
    """Extend the immutable Phase-8 catalog with the two adapter source materials.

    Rejects any base whose ``catalog_digest`` differs from the canonical Phase-8
    cumulative catalog digest (the sole legal base). Cross-checks both descriptors
    against the EXISTING Phase-3 data surface (no new method / capability id; every
    bound method ``read_only``; the structural PIT_REPLAY/ONLINE mode exclusion), then
    adds ONLY each source's handler + serialized-descriptor content materials — **no**
    ``WorkerSpec``, **no** capability, **no** worker-allowlist edit. Every inherited
    Phase-8 worker / skill / capability / content entry passes through byte-identical;
    the final-worker count is therefore unchanged. The merge rejects any id collision,
    sorts the set-like manifests, seals the cumulative ``catalog_digest`` and
    re-validates every cross-reference.
    """
    base_digest = _phase8_catalog_digest()
    if phase8_snapshot.catalog_digest != base_digest:
        raise CatalogError(
            "build_phase9_catalog_snapshot requires the canonical immutable Phase-8 "
            f"catalog ({base_digest}); got base {phase8_snapshot.catalog_digest}"
        )

    # -- cross-check the two descriptors against the existing Phase-3 surface -- #
    surface = phase3_data_surface()
    spec_by_ref = {
        (s.method_id, s.method_version, s.spec_digest): s for s in surface.method_specs
    }
    known_caps = set(data_capability_refs().values())
    _verify_source_descriptor(
        replay_source_descriptor, expected_mode=DataMode.PIT_REPLAY,
        expected_method_ids=_PIT_REPLAY_METHOD_IDS, spec_by_ref=spec_by_ref,
        known_caps=known_caps)
    _verify_source_descriptor(
        live_source_descriptor, expected_mode=DataMode.ONLINE,
        expected_method_ids=_ONLINE_METHOD_IDS, spec_by_ref=spec_by_ref,
        known_caps=known_caps)

    # -- index + verify the four source materials ---------------------------- #
    materials_by_key: dict[tuple[str, str], ResolvedTextMaterial] = {}
    for m in resolved_materials:
        if not isinstance(m, ResolvedTextMaterial):
            raise CatalogError(
                f"phase9 source materials must be text materials; got {type(m).__name__}"
            )
        if m.ref_key in materials_by_key:
            raise CatalogError(f"duplicate phase9 source material {m.ref_key}")
        materials_by_key[m.ref_key] = m

    replay_handler_e, replay_cfg_e = _source_content_entries(
        replay_source_descriptor, _PIT_REPLAY_HANDLER_ID, _PIT_REPLAY_DESCRIPTOR_ID,
        materials_by_key)
    online_handler_e, online_cfg_e = _source_content_entries(
        live_source_descriptor, _ONLINE_HANDLER_ID, _ONLINE_DESCRIPTOR_ID,
        materials_by_key)
    new_content = (replay_handler_e, replay_cfg_e, online_handler_e, online_cfg_e)

    expected_new = {
        (_PIT_REPLAY_HANDLER_ID, "1"), (_PIT_REPLAY_DESCRIPTOR_ID, "1"),
        (_ONLINE_HANDLER_ID, "1"), (_ONLINE_DESCRIPTOR_ID, "1"),
    }
    if set(materials_by_key) != expected_new:
        extra = sorted(set(materials_by_key) - expected_new)
        raise CatalogError(
            f"phase9 catalog received unreviewed extra source material(s): {extra}"
        )

    # -- merge: inherit everything byte-identical + add the four new entries -- #
    base_content_keys = {e.ref_key for e in phase8_snapshot.content_manifest}
    for e in new_content:
        if e.ref_key in base_content_keys:
            raise CatalogError(
                f"phase9 source material {e.ref_key} collides with an inherited "
                "Phase-8 content entry (a new source material must carry a fresh id)"
            )

    content_sorted = tuple(sorted(
        tuple(phase8_snapshot.content_manifest) + new_content, key=lambda e: e.ref_key))
    skill_sorted = tuple(phase8_snapshot.skill_manifest)
    cap_sorted = tuple(phase8_snapshot.capability_manifest)
    workers_sorted = tuple(phase8_snapshot.workers)

    fields: dict[str, Any] = dict(
        catalog_version=PHASE9_CATALOG_VERSION,
        content_manifest=content_sorted,
        skill_manifest=skill_sorted,
        capability_manifest=cap_sorted,
        workers=workers_sorted,
    )
    try:
        digest = WorkerCatalogSnapshot.digest_of_fields(projection="semantic", **fields)
    except (ValueError, TypeError, AttributeError, KeyError):
        digest = "0" * 64
    try:
        snapshot = WorkerCatalogSnapshot(**fields, catalog_digest=digest)
    except Exception as exc:  # surface structural failures as CatalogError
        raise CatalogError(f"phase9 catalog snapshot is not runnable: {exc}") from exc
    validate_catalog_snapshot(snapshot)
    return snapshot


def phase9_catalog_snapshot() -> "WorkerCatalogSnapshot":
    """The canonical cumulative Phase-9 catalog snapshot (the final adapter seal).

    Rebuilds the reviewed Phase-8 catalog the same way its owning module assembles it,
    builds the two adapter source descriptors + materials, and merges them through
    :func:`build_phase9_catalog_snapshot`.
    """
    from guanlan_v2.orchestration import lane_catalog as p8

    base = p8.phase8_catalog_snapshot()
    replay_desc, live_desc, materials = build_phase9_source_materials()
    return build_phase9_catalog_snapshot(
        base,
        replay_source_descriptor=replay_desc,
        live_source_descriptor=live_desc,
        resolved_materials=materials,
    )


# --------------------------------------------------------------------------- #
# Lazy canonical digests (PEP 562) — computed once, never a mutable "latest"    #
# --------------------------------------------------------------------------- #
_PHASE9_REGISTRY_DIGEST: str | None = None
_PHASE9_CATALOG_DIGEST: str | None = None
_PHASE9_INTERNAL_MODELS: "dict[type, str] | None" = None


def __getattr__(name: str) -> "Any":
    global _PHASE9_REGISTRY_DIGEST, _PHASE9_CATALOG_DIGEST, _PHASE9_INTERNAL_MODELS
    if name == "PHASE9_INTERNAL_MODELS":
        if _PHASE9_INTERNAL_MODELS is None:
            _PHASE9_INTERNAL_MODELS = _phase9_internal_models()
        return _PHASE9_INTERNAL_MODELS
    if name == "PHASE9_BASE_REGISTRY_DIGEST":
        return _phase8_registry_digest()
    if name == "PHASE9_REGISTRY_DIGEST":
        if _PHASE9_REGISTRY_DIGEST is None:
            _PHASE9_REGISTRY_DIGEST = build_phase9_registry(
                _phase8_registry_digest()
            ).registry_digest
        return _PHASE9_REGISTRY_DIGEST
    if name == "PHASE9_BASE_CATALOG_DIGEST":
        return _phase8_catalog_digest()
    if name == "PHASE9_CATALOG_DIGEST":
        if _PHASE9_CATALOG_DIGEST is None:
            _PHASE9_CATALOG_DIGEST = phase9_catalog_snapshot().catalog_digest
        return _PHASE9_CATALOG_DIGEST
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
