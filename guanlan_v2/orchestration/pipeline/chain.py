def _deep_decide_preset_ref_doc() -> dict:
    """The deep-decide preset record REFERENCE document (guardrail bytes).

    Loads the committed sealed preset (``presets/v2/luozi_deep_decide_v1.json``)
    through the reviewed Phase-10 loader and binds its identity + semantic
    digest + registered schema key. The catalog thereby NAMES the exact sealed
    preset the deep lane leases against; the preset registry remains the sole
    record authority (the reference never embeds the record body).
    """
    from guanlan_v2.orchestration.pipeline.assembly import (
        PLAN_PRESET_RECORD_V2_SCHEMA_REF,
        PRODUCTION_PRESETS_DIR,
        load_phase10_preset_registry,
    )
    from guanlan_v2.orchestration.pipeline.deep_decide import (
        DEEP_DECIDE_PRESET_ID,
        DEEP_DECIDE_PRESET_VERSION,
    )

    record = load_phase10_preset_registry(PRODUCTION_PRESETS_DIR).get(
        DEEP_DECIDE_PRESET_ID)
    if not isinstance(record, PlanPresetRecordV2):
        raise CatalogError(
            f"committed preset {DEEP_DECIDE_PRESET_ID!r} is not a "
            "PlanPresetRecordV2; the catalog reference refuses to name it"
        )
    return {
        "kind": "plan_preset_record_ref",
        "preset_id": DEEP_DECIDE_PRESET_ID,
        "preset_version": DEEP_DECIDE_PRESET_VERSION,
        "record_digest": record.semantic_digest(),
        "schema_key": PLAN_PRESET_RECORD_V2_SCHEMA_REF.key,
    }


def _serialize_preset_ref_doc(doc: dict) -> bytes:
    return json.dumps(
        doc, sort_keys=True, ensure_ascii=False, separators=(",", ":")
    ).encode("utf-8")


def build_phase10_materials() -> tuple[
    dict[str, ContentRef], tuple[ResolvedTextMaterial, ...]
]:
    """Build the four Phase-10 catalog materials (three handlers + the preset ref).

    Returns ``(refs_by_id, materials)`` with digests computed from the exact
    bytes via the reviewed :func:`build_text_material` (never pinned by hand).
    """
    refs: dict[str, ContentRef] = {}
    materials: list[ResolvedTextMaterial] = []
    for material_id, raw in sorted(_CAND_HANDLER_BYTES.items()):
        ref, mat = build_text_material(
            id=material_id, version="1", kind="handler", raw=raw)
        refs[material_id] = ref
        materials.append(mat)
    ref, mat = build_text_material(
        id=DEEP_DECIDE_PRESET_REF_MATERIAL_ID, version="1", kind="guardrail",
        raw=_serialize_preset_ref_doc(_deep_decide_preset_ref_doc()))
    refs[DEEP_DECIDE_PRESET_REF_MATERIAL_ID] = ref
    materials.append(mat)
    return refs, tuple(materials)


def build_phase10_worker_specs(
    refs: dict[str, ContentRef],
) -> tuple[WorkerSpec, ...]:
    """The three reviewed ``cand.*`` DETERMINISTIC WorkerSpecs (module docstring
    records the params/mode/lane/read-category decisions)."""
    persona = {
        "cand.v4": (
            "Deterministic v4-ranking candidate reader — top-N slate, "
            "advisory-only, zero trading authority"
        ),
        "cand.lane0": (
            "Deterministic Lane-0 rotation-leader candidate reader — honest "
            "typed refusal in v1 (no upstream leader codes), zero trading authority"
        ),
        "cand.model": (
            "Deterministic model-variant candidate reader — named-variant "
            "top-N slate, advisory-only, zero trading authority"
        ),
    }
    specs = []
    for worker_id in CAND_WORKER_IDS:
        specs.append(WorkerSpec(
            id=worker_id,
            catalog_role="final",
            selection_scope="dynamic_allowed",
            lane="quant",
            persona=persona[worker_id],
            tier=Tier.READER,
            execution=ExecutionSpec(
                kind=ExecutionKind.DETERMINISTIC,
                handler_ref=refs[CAND_HANDLER_IDS[worker_id]],
            ),
            read_categories=("market_data",),
            params_schema_ref=None,
            inputs=(),
            outputs=(OutputBinding(
                name="primary", schema_ref=_CANDIDATE_SLATE_SCHEMA_REF),),
            evidence_policy=EvidencePolicy(
                tool_calls=ToolCallRequirement.FORBIDDEN,
                require_input_refs=False,
                require_number_anchors=False,
                allow_unsourced_numbers=False,
                optional_data_may_degrade=True,
            ),
            supported_modes=(DataMode.ONLINE,),
            can_emit_decision=False,
            decision_authority="none",
        ))
    return tuple(specs)


def build_phase10_catalog_snapshot(
    phase9_snapshot: "WorkerCatalogSnapshot",
    *,
    resolved_materials: tuple[ResolvedTextMaterial, ...],
) -> "WorkerCatalogSnapshot":
    """Extend the immutable Phase-9 catalog with the Phase-10 pipeline additions.

    Rejects any base whose ``catalog_digest`` differs from the canonical
    Phase-9 cumulative catalog digest (the sole legal base). Verifies the
    supplied materials are EXACTLY the four reviewed Phase-10 materials (byte
    digests recomputed, preset-reference bytes re-parsed and cross-checked
    against the committed preset registry so a preset edit without a catalog
    re-freeze is loud), builds the three ``cand.*`` WorkerSpecs over the
    verified handler refs, and merges — every inherited Phase-9 worker / skill /
    capability / content entry passes through byte-identical; new ids must not
    collide; the manifests are sorted; the cumulative ``catalog_digest`` is
    sealed and every cross-reference re-validated.
    """
    base_digest = _phase9_catalog_digest()
    if phase9_snapshot.catalog_digest != base_digest:
        raise CatalogError(
            "build_phase10_catalog_snapshot requires the canonical immutable "
            f"Phase-9 catalog ({base_digest}); got base "
            f"{phase9_snapshot.catalog_digest}"
        )

    # -- index + verify the four Phase-10 materials --------------------------- #
    expected_keys = {(mid, "1") for mid in _CAND_HANDLER_BYTES} | {
        (DEEP_DECIDE_PRESET_REF_MATERIAL_ID, "1")
    }
    by_key: dict[tuple[str, str], ResolvedTextMaterial] = {}
    for m in resolved_materials:
        if not isinstance(m, ResolvedTextMaterial):
            raise CatalogError(
                f"phase10 materials must be text materials; got {type(m).__name__}"
            )
        if m.ref_key in by_key:
            raise CatalogError(f"duplicate phase10 material {m.ref_key}")
        if catalog_material_digest(m) != m.ref.content_digest:
            raise CatalogError(
                f"phase10 material {m.ref_key} digest does not recompute from "
                "its bytes"
            )
        by_key[m.ref_key] = m
    if set(by_key) != expected_keys:
        raise CatalogError(
            "phase10 catalog takes exactly the four reviewed materials "
            f"{sorted(expected_keys)}; got {sorted(by_key)}"
        )
    for mid, raw in _CAND_HANDLER_BYTES.items():
        mat = by_key[(mid, "1")]
        if mat.kind != "handler" or mat.raw_utf8 != raw:
            raise CatalogError(
                f"phase10 handler material {mid}@1 drifted from the reviewed bytes"
            )
    pref = by_key[(DEEP_DECIDE_PRESET_REF_MATERIAL_ID, "1")]
    if pref.kind != "guardrail":
        raise CatalogError(
            "the deep-decide preset reference must be a guardrail material"
        )
    try:
        doc = json.loads(pref.raw_utf8.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise CatalogError(
            f"the deep-decide preset reference bytes are not canonical JSON: {exc}"
        ) from exc
    expected_doc = _deep_decide_preset_ref_doc()
    if doc != expected_doc:
        raise CatalogError(
            "the deep-decide preset reference does not match the committed sealed "
            f"preset (got {doc}, committed {expected_doc}); a preset change is a "
            "reviewed catalog re-freeze, never a silent drift"
        )

    # -- workers: exactly the three new cand.* finals ------------------------- #
    refs = {key[0]: m.ref for key, m in by_key.items()}
    new_workers = build_phase10_worker_specs(refs)
    base_ids = {w.id for w in phase9_snapshot.workers}
    for w in new_workers:
        if w.id in base_ids:
            raise CatalogError(
                f"new candidate worker {w.id!r} collides with an inherited "
                "Phase-9 worker id"
            )

    # -- content entries + merge (inherit byte-identical, sort, seal) ---------- #
    new_content = tuple(
        ContentManifestEntry(
            ref=by_key[key].ref,
            kind=by_key[key].kind,
            name=key[0],
            description=(
                f"phase10 pipeline material {key[0]}@{key[1]} ({by_key[key].kind})."
            ),
            source_identity=PHASE10_SOURCE_IDENTITY,
        )
        for key in sorted(by_key)
    )
    base_content_keys = {e.ref_key for e in phase9_snapshot.content_manifest}
    for e in new_content:
        if e.ref_key in base_content_keys:
            raise CatalogError(
                f"phase10 material {e.ref_key} collides with an inherited "
                "Phase-9 content entry"
            )

    content_sorted = tuple(sorted(
        tuple(phase9_snapshot.content_manifest) + new_content,
        key=lambda e: e.ref_key))
    workers_sorted = tuple(sorted(
        tuple(phase9_snapshot.workers) + new_workers, key=lambda w: w.id))

    fields: dict[str, Any] = dict(
        catalog_version=PHASE10_CATALOG_VERSION,
        content_manifest=content_sorted,
        skill_manifest=tuple(phase9_snapshot.skill_manifest),
        capability_manifest=tuple(phase9_snapshot.capability_manifest),
        workers=workers_sorted,
    )
    try:
        digest = WorkerCatalogSnapshot.digest_of_fields(projection="semantic", **fields)
    except (ValueError, TypeError, AttributeError, KeyError):
        digest = "0" * 64
    try:
        snapshot = WorkerCatalogSnapshot(**fields, catalog_digest=digest)
    except Exception as exc:  # surface structural failures as CatalogError
        raise CatalogError(f"phase10 catalog snapshot is not runnable: {exc}") from exc
    validate_catalog_snapshot(snapshot)
    return snapshot


