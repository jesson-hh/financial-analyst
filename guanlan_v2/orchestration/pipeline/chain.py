"""Phase 10 · Task 11 — the cumulative registry/catalog chain node.

Phase 10 is the product-pipeline phase (帷幄选股 A-chain + 落子买卖点 B-chain +
公共件 C). This module owns the reviewed *classification + chain* seal of that
phase — the node AFTER the Phase-9 adapter seal in the framework's linear
registry/catalog lineage (P2 → … → P8 → P9 → P10) — built as a pure ADDITION
over the sealed Phase-9 chain (never a fork, never a "latest" alias), mirroring
the ``adapters.chain`` (P9) / ``lane_catalog`` (P8) precedents:

* :data:`PHASE10_PUBLIC_MODELS` — the six public pipeline payloads the Phase-10
  cumulative registry resolves a :class:`SchemaRef` to. Five register at ``@1``
  under their own class names; the sixth,
  :class:`~guanlan_v2.orchestration.pipeline.assembly.PlanPresetRecordV2`,
  registers under the REVIEWED identity **``PlanPresetRecord@2``** (Amendment 3;
  ``assembly.PLAN_PRESET_RECORD_V2_SCHEMA_REF`` pins ``name="PlanPresetRecord"``)
  — a version bump of the Phase-7 preset-record schema family, not a new family.
  The registry keys strictly by class ``__name__``, so registration goes through
  a function-local registration identity (a 1:1 field-for-field subclass named
  ``PlanPresetRecord``) that never leaves :func:`build_phase10_registry` — the
  discovery firewall keeps seeing exactly the reviewed ``PlanPresetRecordV2``.
* :data:`PHASE10_INTERNAL_MODELS` — the reviewed ``type -> reason`` map of every
  Phase-10 ContractModel deliberately NOT registered (nine value carriers).
  ``DeepDecideBindings`` / ``MaterializedDeepDecide`` / ``CandidatePorts`` and
  the params dataclasses are plain (data)classes, invisible to the ContractModel
  firewall **by design** (the plan's Task-11 clause) — they can never be
  registered and are not listed here.
* :func:`build_phase10_registry` — a *fresh sealed* cumulative registry over the
  exact Phase-9 cumulative set + the six Phase-10 publics; the supplied base
  digest is verified against ``adapters.chain.PHASE9_REGISTRY_DIGEST`` *before
  any registration*; inherited JSON Schemas stay byte-identical to their
  Phase-<=9 goldens; :data:`PHASE10_REGISTRY_DIGEST` is frozen.
* :func:`build_phase10_catalog_snapshot` — extends the immutable Phase-9 catalog
  with exactly the three ``cand.*`` DETERMINISTIC WorkerSpecs (tier ``READER``,
  ``can_emit_decision=False``, ``selection_scope="dynamic_allowed"``, output
  ``CandidateSlate@1``) plus their three trusted handler materials and ONE
  guardrail material carrying the deep-decide preset record REFERENCE (preset
  id/version + the committed record's semantic digest + its registered schema
  key) — the catalog names the sealed preset it schedules against without ever
  duplicating the preset registry's authority. Every inherited entry passes
  through byte-identical; ``count_final_workers`` = the Phase-8 (== Phase-9)
  count + 3.

**Reviewed spec decisions (recorded for the chain test + report):**

* ``params_schema_ref=None`` on all three ``cand.*`` specs — the Task-2 params
  dual-path ruling lands on FACTORY-BOUND: the frozen ``Cand*Params`` are plain
  dataclasses (registering them would exceed the reviewed six-model surface), so
  a plan node scheduling a ``cand.*`` worker carries NO params (Phase 1 refuses
  node params without a schema ref) and the handler's ``merged_with`` node-param
  half stays dormant until a reviewed params schema lands.
* ``supported_modes=(DataMode.ONLINE,)`` — the ratified-D5 production ranking
  reader reads the LATEST ranking artifact (``v4_ranking_latest.parquet``);
  it implements no PIT discipline, so declaring ``PIT_REPLAY`` would be a lie.
* ``read_categories=("market_data",)`` mirrors the Lane-0 deterministic
  ``market.factor`` reader (the ranking artifact IS market data, reached through
  the injected :class:`~guanlan_v2.orchestration.pipeline.candidates.RankingReader`
  port, never a capability call — ``tool_calls=FORBIDDEN``).
* ``lane="quant"`` — deterministic quantitative ranking readers.

**EventType decision (explicit).** Phase 10 adds **no** ``EventType`` member and
mints **no** new Phase-3 data method id; a test pins the frozen value set.

Both goldens (``phase10_schema_manifest_v1.json`` /
``phase10_catalog_manifest_v1.json``) are hand-frozen from a one-off
verification run and never auto-regenerated by a test.
"""
