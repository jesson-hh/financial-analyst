    global _PHASE10_REGISTRY_DIGEST, _PHASE10_CATALOG_DIGEST
    global _PHASE10_INTERNAL_MODELS
    if name == "PHASE10_INTERNAL_MODELS":
        if _PHASE10_INTERNAL_MODELS is None:
            _PHASE10_INTERNAL_MODELS = _phase10_internal_models()
