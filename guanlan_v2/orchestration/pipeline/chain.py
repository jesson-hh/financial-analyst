def _registered_plan_preset_record_v2() -> "type[PlanPresetRecordV2]":
    """The function-local REGISTRATION identity of ``PlanPresetRecordV2``.

    The cumulative registry keys strictly by class ``__name__``
    (``runtime_contracts.Phase2RuntimeRegistry.register``), and the reviewed
    registered identity is ``PlanPresetRecord@2`` (Amendment 3;
    ``assembly.PLAN_PRESET_RECORD_V2_SCHEMA_REF``) — the v2 of the Phase-7
    schema family, NOT a new ``PlanPresetRecordV2`` family. This 1:1
    field-for-field subclass carries the base name for registration only; it
    adds no field, no validator, and never leaves
    :func:`build_phase10_registry`, so the discovery/classification firewalls
    keep seeing exactly the reviewed ``assembly.PlanPresetRecordV2``. Its JSON
    Schema is deterministic across constructions (same fields, same title), so
    the golden digest is stable.
    """
    return type(
        "PlanPresetRecord",
        (PlanPresetRecordV2,),
        {"__module__": __name__, "__doc__": PlanPresetRecordV2.__doc__},
    )


def build_phase10_registry(
    expected_phase9_digest: "DigestHex",
) -> "Phase2RuntimeRegistry":
    """Build + seal the cumulative Phase-10 registry, pinned to the Phase-9 base.

    Verifies ``expected_phase9_digest`` against the actual sealed Phase-9
    cumulative registry digest first — any other base digest is rejected
    *before any registration* — then registers the complete inherited
    cumulative set (Phase 1 → Phase 9) followed by the six Phase-10 publics
    (:data:`PHASE10_PUBLIC_MODELS`; ``PlanPresetRecordV2`` through its
    ``PlanPresetRecord@2`` registration identity) into a *fresh*
    :class:`~guanlan_v2.orchestration.runtime_contracts.Phase2RuntimeRegistry`
    and seals it. No upstream registry is mutated; inherited JSON Schemas stay
    byte-identical to their Phase-<=9 goldens; there is no "latest" alias.
    """
    from guanlan_v2.orchestration import (
        bootstrap,
        lane_catalog as p8,
        phase7_registry as p7,
        shadow,
        trial,
    )
    from guanlan_v2.orchestration.adapters import chain as p9
    from guanlan_v2.orchestration.data.schema_registry import (
        PHASE3_PUBLIC_MODELS as _DATA_PUBLIC,
    )
    from guanlan_v2.orchestration.memory.schema_registry import (
        PHASE3_MEMORY_PUBLIC_MODELS as _MEM_PUBLIC,
    )
    from guanlan_v2.orchestration.runtime_contracts import (
        Phase2RuntimeRegistry,
        phase2_public_models,
    )

    actual = p9.PHASE9_REGISTRY_DIGEST
    if expected_phase9_digest != actual:
        raise Phase10RegistryError(
            "build_phase10_registry requires the exact Phase-9 registry digest "
            f"{actual!r}; got {expected_phase9_digest!r}"
        )
    reg = Phase2RuntimeRegistry()
    for model in (
        tuple(phase2_public_models())
        + tuple(_DATA_PUBLIC)
        + tuple(_MEM_PUBLIC)
        + tuple(trial.PHASE4_PUBLIC_MODELS)
        + tuple(bootstrap.PHASE5_PUBLIC_MODELS)
        + tuple(shadow.PHASE6_PUBLIC_MODELS)
        + tuple(p7.PHASE7_PUBLIC_MODELS)
        + tuple(p8.PHASE8_PUBLIC_MODELS)
        + tuple(p9.PHASE9_PUBLIC_MODELS)
    ):
        reg.register(model)
    for model in PHASE10_PUBLIC_MODELS:
        if model is PlanPresetRecordV2:
            reg.register(_registered_plan_preset_record_v2())
        else:
            reg.register(model)
    reg.seal()
    return reg


