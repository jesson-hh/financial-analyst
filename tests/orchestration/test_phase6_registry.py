    # through TargetPosition@1, so it is INTERNAL (nested) and never registered.
    assert shadow.TrancheTrigger in shadow.PHASE6_INTERNAL_MODELS
    assert shadow.TrancheTrigger not in shadow.PHASE6_PUBLIC_MODELS
    assert "schema_version" not in shadow.TrancheTrigger.model_fields
    reason = shadow.PHASE6_INTERNAL_MODELS[shadow.TrancheTrigger].lower()
