def _dt() -> datetime:
    return datetime(2026, 7, 15, 1, 30, tzinfo=UTC)


def _text_material(id: str, kind: str):
    raw = f"You are {id}.".encode("utf-8")
    tmp = ResolvedTextMaterial(
        ref=ContentRef(id=id, version="1", content_digest="0" * 64), kind=kind, raw_utf8=raw
    )
    digest = catalog_material_digest(tmp)
    ref = ContentRef(id=id, version="1", content_digest=digest)
    return ref, ResolvedTextMaterial(ref=ref, kind=kind, raw_utf8=raw)


def _decision_catalog(*, can_emit_decision: bool):
    pref, pmat = _text_material("dec.worker.prompt", "prompt")
    pentry = ContentManifestEntry(
        ref=pref, kind="prompt", name="dec.worker", description="d", source_identity="gl.src"
    )
    worker = WorkerSpec(
        id="dec.worker",
        catalog_role="final",
        selection_scope="dynamic_allowed",
        lane="decision",
        persona="p",
        tier=Tier.WRITER,
        execution=ExecutionSpec(kind=ExecutionKind.LLM, model_tier="reasoner"),
        system_prompt_ref=pref,
        inputs=(),
        outputs=(OutputBinding(
            name="primary",
            schema_ref=SchemaRef(name="PortfolioTargetProposal", version="1"),
        ),),
        evidence_policy=EvidencePolicy(),
        supported_modes=(DataMode.ONLINE,),
        can_emit_decision=can_emit_decision,
        decision_authority="advisory_only" if can_emit_decision else "none",
    )
    return build_catalog_snapshot(
        catalog_version="cat.v1",
        content_manifest=(pentry,),
        skill_manifest=(),
        capability_manifest=(),
        workers=(worker,),
        resolved_material=(pmat,),
    )


def _context() -> ContextSnapshot:
    binding = build_empty_memory_binding()
    clock = ClockSpec(as_of=_dt(), timezone="Asia/Shanghai", calendar_id="cn_a_share")
    dc = DataContext(
        as_of=_dt(), clock=clock, mode=DataMode.ONLINE, backend=DataBackend.LIVE,
        strict_pit=False, calendar_id="cn_a_share",
        resolved_vendor_chains={"prices": ("tushare",)},
        source_config_digest=_D["a"], source_registry_digest=_D["b"],
        routing_snapshot_digest=_D["c"], data_snapshot_id="snap-1",
        data_snapshot_content_digest=_D["d"], built_at=_dt(),
    )
    return ContextSnapshot.build(
        snapshot_id="ctx-1", data_context=dc, memory_snapshot_id="ms-1",
        memory_snapshot_hash=binding.snapshot_hash,
        past_context_hash=binding.past_context_hash,
        memory_snapshot_ref=binding.memory_snapshot_ref,
        memory_selection_ref=binding.memory_selection_ref,
        runtime_requirements_ref=None, built_at=_dt(),
    )


