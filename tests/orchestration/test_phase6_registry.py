def test_unauthorized_decision_sink_bites_under_the_phase6_registry():
    registry = shadow.build_phase6_registry(shadow.PHASE6_BASE_REGISTRY_DIGEST)
    # PortfolioTargetProposal@1 resolves in the Phase-6 registry (the class name was
    # frozen in spec._DECISION_CLASS_SCHEMAS for exactly this — zero spec.py edits).
    registry.resolve(SchemaRef(name="PortfolioTargetProposal", version="1"))
    context = _context()
    catalog = _decision_catalog(can_emit_decision=False)
    draft = _decision_draft(catalog, registry, context)
    report = validate_plan_draft(
        draft, request=_request(), context=context, catalog=catalog,
        schema_registry=registry,
    )
    codes = {i.code for i in report.issues}
    assert not report.valid and "unauthorized_decision_sink" in codes


