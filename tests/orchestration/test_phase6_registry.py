"""Phase 6 · Task 10 — cumulative Phase-6 registry / catalog chain + goldens.

Locks the linear registry/catalog chain the shadow-consumer phase contributes,
built as a pure ADDITION over the sealed Phase-5 chain (never a fork, never a
"latest" alias):

* ``build_phase6_registry(expected_phase5_digest)`` builds a *fresh sealed*
  cumulative registry over the exact Phase-5 cumulative set (Phase-1 public +
  Phase-2 runtime facts + Phase-3 data + Phase-3 memory + Phase-4
  Evaluator-Optimizer + Phase-5 Bootstrap Lane 0) plus the reviewed
  :data:`PHASE6_PUBLIC_MODELS` (the ten shadow-consumer payloads); a wrong base
  digest is rejected before any registration; inherited entries stay
  byte-identical to their Phase-≤5 goldens; the digest is registration-order
  independent and matches the hand-reviewed golden;
* ``build_phase6_catalog_snapshot(phase5_snapshot, expected_phase5_digest)`` is
  the **explicit identity chain node** — Phase 6 adds ZERO workers and ZERO
  capabilities (a red-line fact: no live order/signal write tool enters through
  this phase). It verifies its base and returns the snapshot unchanged;
  ``PHASE6_CATALOG_DIGEST`` is RECORDED equal to ``PHASE5_CATALOG_DIGEST`` (never
  aliased);
* the Phase-6 public/internal partition over the two Phase-6 contract modules
  (``shadow`` + ``adapters.luozi``) is exhaustive and disjoint — ``TrancheTrigger``
  is a nested frozen sub-model (no independent ``schema_version``) classified
  INTERNAL, entering the registry only through ``TargetPosition@1``'s JSON schema;
* the sink-authorization invariant now bites for real: a ``PlanDraft`` whose
  sink's primary output schema is ``PortfolioTargetProposal@1`` (resolvable in the
  Phase-6 registry) validates only when the emitting worker has
  ``can_emit_decision=True`` — otherwise Phase-1 ``validate_plan_draft`` reports
  ``unauthorized_decision_sink`` with ZERO ``spec.py`` changes;
* old Plans binding any upstream digest stay resolvable side-by-side through the
  ``SchemaRegistryResolver`` — no reinterpretation, no "latest".

Goldens are NEVER auto-regenerated by tests: a changed manifest is a reviewed
contract change regenerated by hand and re-reviewed.

Run: ``pytest tests/orchestration/test_phase6_registry.py -v``
"""
