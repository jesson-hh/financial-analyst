#: the five Phase-7 contract modules the completeness firewall governs.
PHASE7_CONTRACT_MODULES = (
    "guanlan_v2.orchestration.orchestrator",
    "guanlan_v2.orchestration.plan_presets",
    "guanlan_v2.orchestration.plan_diff",
    "guanlan_v2.orchestration.approval",
    "guanlan_v2.orchestration.planner_gateway",
)

#: the eight reviewed names the registered Phase-7 surface must equal.
EXPECTED_PUBLIC_NAMES = frozenset({
    "PlannerSpec", "PlannerAttemptRecord", "PlannerRunRecord", "PlanPresetRecord",
    "PlanDiffEntry", "PlanDiff", "PendingPlanApproval", "ApprovalLease",
})

#: the six reviewed INTERNAL Phase-7 contract names the partition must equal.
EXPECTED_INTERNAL_NAMES = frozenset({
    "PlannerDependencyEnvelope", "PlannerNodeEnvelope", "PlannerDraftEnvelope",
    "PlanPresetManifestEntry", "ApprovalJournalRow", "LeaseRevocation",
})

#: the three catalog-owned planner material ids (@1).
EXPECTED_CONTENT_MATERIAL_KEYS = ("orchestrator.planner.guardrail@1", "orchestrator.planner.prompt@1")
EXPECTED_SKILL_MATERIAL_KEYS = ("orchestrator.planner.skill@1",)

#: still-deferred Phase-8 payloads — absent from every registry in the chain.
STILL_DEFERRED_NAMES = ("DebateMessage",)


def _load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _discover_phase7_contract_models() -> set[type]:
    found: set[type] = set()
    for module_name in PHASE7_CONTRACT_MODULES:
        module = importlib.import_module(module_name)
        for obj in vars(module).values():
            if (
                inspect.isclass(obj)
                and issubclass(obj, ContractModel)
                and obj not in (ContractModel, DigestModel)
                and obj.__module__ == module_name
                and not obj.__name__.startswith("_")
            ):
                found.add(obj)
    return found


