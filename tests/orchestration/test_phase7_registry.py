def test_phase7_catalog_adds_only_planner_materials_no_worker():
    base = shadow.phase6_catalog_snapshot()
    snap = p7.phase7_catalog_snapshot()
    assert snap.catalog_digest == p7.PHASE7_CATALOG_DIGEST
    # ZERO new workers / capabilities: the Planner is not a selectable worker.
    assert count_final_workers(snap) == count_final_workers(base)
    assert snap.workers == base.workers
    assert snap.capability_manifest == base.capability_manifest
    # exactly three new materials (two content + one skill).
    base_content = {e.ref_key for e in base.content_manifest}
    base_skill = {e.ref_key for e in base.skill_manifest}
    new_content = {e.ref_key for e in snap.content_manifest} - base_content
    new_skill = {e.ref_key for e in snap.skill_manifest} - base_skill
    assert {f"{i}@{v}" for i, v in new_content} == set(EXPECTED_CONTENT_MATERIAL_KEYS)
    assert {f"{i}@{v}" for i, v in new_skill} == set(EXPECTED_SKILL_MATERIAL_KEYS)


def test_planner_materials_resolve_with_matching_kind_and_digest():
    snap = p7.phase7_catalog_snapshot()
    materials = {m.ref_key: m for m in p7.load_planner_materials()}
    content_by_key = {e.ref_key: e for e in snap.content_manifest}
    skill_by_key = {e.ref_key: e for e in snap.skill_manifest}
    # every planner material resolves into its manifest entry with kind + digest.
    for key, mat in materials.items():
        assert isinstance(mat, ResolvedTextMaterial)
        recomputed = catalog_material_digest(mat)
        assert mat.ref.content_digest == recomputed
        if mat.kind == "skill":
            entry = skill_by_key[key]
            assert entry.ref.content_digest == recomputed
        else:
            entry = content_by_key[key]
            assert entry.kind == mat.kind
            assert entry.ref.content_digest == recomputed
        assert entry.source_identity == "orchestrator.planner"


