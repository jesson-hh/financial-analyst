"""Phase 7 · Task 9 — cumulative Phase-7 registry / catalog chain + planner materials.

Locks the linear registry/catalog chain the dynamic-Planner phase contributes,
built as a pure ADDITION over the sealed Phase-6 chain (never a fork, never a
"latest" alias):

* ``build_phase7_registry(expected_phase6_digest)`` builds a *fresh sealed*
  cumulative registry over the exact Phase-6 cumulative set plus the reviewed
  :data:`PHASE7_PUBLIC_MODELS` (the eight dynamic-Planner payloads); a wrong base
  digest is rejected before any registration; inherited entries stay
  byte-identical to their Phase-<=6 goldens; the digest is registration-order
  independent and matches the hand-reviewed golden;
* ``build_phase7_catalog_snapshot(phase6_snapshot, *, planner_materials)`` adds
  ONLY the catalog-owned planner content/skill/guardrail manifest entries and
  **zero WorkerSpec** — the Planner is deliberately not a selectable worker, so
  ``count_final_workers`` is unchanged from Phase 6 while three new materials
  resolve with matching kind + digest;
* the Phase-7 public/internal partition over the five Phase-7 contract modules
  (``orchestrator`` / ``plan_presets`` / ``plan_diff`` / ``approval`` /
  ``planner_gateway``) is exhaustive and disjoint;
* ``build_phase7_planner_spec(catalog)`` derives its refs from the Phase-7 catalog
  manifests by exact id/version/digest and freezes as ``planner_spec_digest``;
* no ``EventType`` member was added (stays 25) and no Phase-1 absence/
  deferred-payload guard was touched (nothing pins a Phase-7 model).

Goldens are NEVER auto-regenerated by tests: a changed manifest is a reviewed
contract change regenerated by hand and re-reviewed.

Run: ``pytest tests/orchestration/test_phase7_registry.py -v``
"""
