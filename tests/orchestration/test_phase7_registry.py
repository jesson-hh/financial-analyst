def test_public_and_internal_partition_the_module_surface_exactly():
    discovered = _discover_phase7_contract_models()
    public = set(p7.PHASE7_PUBLIC_MODELS)
    internal = set(p7.PHASE7_INTERNAL_MODELS)
    classified = public | internal
    assert not (public & internal), "a Phase-7 contract cannot be both registered and internal"
    unclassified = discovered - classified
    assert not unclassified, (
        "unreviewed Phase-7 public contracts: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in unclassified))
    )
    phantom = classified - discovered
    assert not phantom, (
        "classified models not discovered in the five Phase-7 modules: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in phantom))
    )
    assert classified == discovered
    assert len(public) + len(internal) == len(discovered)


