def test_registry_matches_the_frozen_golden_entry_for_entry():
    assert SCHEMA_GOLDEN.exists(), f"missing golden: {SCHEMA_GOLDEN}"
    doc = _load_json(SCHEMA_GOLDEN)
    assert doc["algorithm"] == CJSON_VERSION == "sha256+cjson-v1"
    assert doc["base_registry_digest"] == shadow.PHASE6_REGISTRY_DIGEST
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    reg = p7.build_phase7_registry(p7.PHASE7_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    assert set(manifest) == set(golden), (
        "phase7 registry key set drifted from phase7_schema_manifest_v1.json; "
        "regenerate + re-review by hand if intended"
    )
    for key in sorted(golden):
        assert manifest[key] == golden[key], f"JSON-schema digest drift for {key}"
    assert reg.registry_digest == doc["registry_digest"]


def test_inherited_entries_are_byte_identical_to_the_phase6_golden():
    phase6_doc = _load_json(GOLDEN_DIR / "phase6_schema_manifest_v1.json")
    phase6 = {e["key"]: e["json_schema_digest"] for e in phase6_doc["entries"]}
    reg = p7.build_phase7_registry(p7.PHASE7_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    # every Phase-6 (cumulative) key is inherited byte-identical …
    for key, digest in phase6.items():
        assert manifest[key] == digest, f"inherited schema {key} drifted in phase7"
    # … and the only new keys are exactly the eight Phase-7 public contracts.
    new_keys = set(manifest) - set(phase6)
    assert {k.split("@")[0] for k in new_keys} == EXPECTED_PUBLIC_NAMES
    assert len(new_keys) == 8


def test_inherited_entries_are_byte_identical_across_every_upstream_manifest():
    """Walk ALL phase schema goldens — every inherited key stays byte-identical."""
    reg = p7.build_phase7_registry(p7.PHASE7_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    upstream_goldens = (
        "schema_manifest_v1.json",
        "runtime_schema_manifest_v1.json",
        "data_schema_manifest_v1.json",
        "phase3_full_schema_manifest_v1.json",
        "phase4_schema_manifest_v1.json",
        "phase5_schema_manifest_v1.json",
        "phase6_schema_manifest_v1.json",
    )
    for fname in upstream_goldens:
        path = GOLDEN_DIR / fname
        if not path.exists():
            continue
        doc = _load_json(path)
        for e in doc.get("entries", []):
            key = e["key"]
            if key in manifest:
                assert manifest[key] == e["json_schema_digest"], (
                    f"inherited schema {key} drifted from {fname} in phase7"
                )


def test_new_public_contract_digests_are_recomputable_from_the_models():
    doc = _load_json(SCHEMA_GOLDEN)
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    for model in p7.PHASE7_PUBLIC_MODELS:
        key = f"{model.__name__}@{model.model_fields['schema_version'].default}"
        assert golden[key] == content_digest(model.model_json_schema())


def test_upstream_goldens_are_byte_unchanged():
    for fname, sha in UPSTREAM_GOLDEN_SHA256.items():
        raw = (GOLDEN_DIR / fname).read_bytes()
        assert hashlib.sha256(raw).hexdigest() == sha, (
            f"upstream golden {fname} changed — Phase 7 must never regenerate it"
        )


