def test_planner_spec_derivation_is_deterministic_and_by_ref():
    catalog = p7.phase7_catalog_snapshot()
    spec_a = p7.build_phase7_planner_spec(catalog)
    spec_b = p7.build_phase7_planner_spec(catalog)
    assert spec_a.semantic_digest() == spec_b.semantic_digest()
    assert spec_a.model_tier == "reasoner_deep"
    assert spec_a.max_generation_attempts == 2
    assert spec_a.output_contract == "planner-output-v1"
    assert spec_a.skills, "planner spec skills must be non-empty"
    # refs are derived from the catalog manifests by exact id/version/digest.
    content_by_key = {e.ref_key: e for e in catalog.content_manifest}
    skill_by_key = {e.ref_key: e for e in catalog.skill_manifest}
    prompt_entry = content_by_key[("orchestrator.planner.prompt", "1")]
    assert spec_a.system_prompt_ref == prompt_entry.ref
    guardrail_entry = content_by_key[("orchestrator.planner.guardrail", "1")]
    assert guardrail_entry.ref in spec_a.guardrail_refs
    skill_entry = skill_by_key[("orchestrator.planner.skill", "1")]
    assert any(sb.skill_ref == skill_entry.ref for sb in spec_a.skills)


