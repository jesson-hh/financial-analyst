def test_build_phase7_catalog_rejects_a_non_canonical_base():
    from guanlan_v2.orchestration.catalog import CatalogError

    materials = p7.load_planner_materials()
    # a Phase-4 catalog (a genuinely different digest) is not the legal Phase-6
    # base. NB: the Phase-5/6 catalogs share a digest (Phase 6 is an identity node),
