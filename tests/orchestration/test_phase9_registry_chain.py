def _load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _discover_phase9_contract_models() -> set[type]:
    found: set[type] = set()
    for module_name in PHASE9_CONTRACT_MODULES:
        try:
            module = importlib.import_module(module_name)
        except ModuleNotFoundError:
            continue  # a later task creates it; inert until then
        for obj in vars(module).values():
            if (
                inspect.isclass(obj)
                and issubclass(obj, ContractModel)
                and obj not in (ContractModel, DigestModel)
                and obj.__module__ == module_name
                and not obj.__name__.startswith("_")
            ):
                found.add(obj)
    return found


