def test_descriptors_bind_only_existing_method_and_capability_ids():
    from guanlan_v2.orchestration.data.catalog import (
        data_capability_refs,
        phase3_data_surface,
    )

    surface = phase3_data_surface()
    known_method_refs = {
        (s.method_id, s.method_version, s.spec_digest) for s in surface.method_specs
    }
    known_caps = set(data_capability_refs().values())
    replay_desc, live_desc, _mats = ch.build_phase9_source_materials()
    for desc in (replay_desc, live_desc):
        for mref in desc.method_refs:
            assert (mref.id, mref.version, mref.content_digest) in known_method_refs, (
                f"source {desc.source_id} mints a NEW method id {mref.id}@{mref.version}"
            )
        for cref in desc.method_capability_refs:
            assert cref in known_caps, (
                f"source {desc.source_id} mints a NEW capability {cref.id}@{cref.version}"
            )


def test_descriptors_are_mode_exclusive_and_read_only_no_write_capability():
    from guanlan_v2.orchestration.enums import DataMode
    from guanlan_v2.orchestration.data.catalog import phase3_data_surface

    surface = phase3_data_surface()
    spec_by_ref = {
        (s.method_id, s.method_version, s.spec_digest): s for s in surface.method_specs
    }
    replay_desc, live_desc, _mats = ch.build_phase9_source_materials()
    # the structural mode exclusion — a PIT_REPLAY read can never resolve the ONLINE
    # source and vice versa.
    assert replay_desc.supported_modes == (DataMode.PIT_REPLAY,)
    assert live_desc.supported_modes == (DataMode.ONLINE,)
    # every bound method spec is read-only — the snapshot carries NO order/signal write.
    write_markers = ("order", "trade", "write", "submit", "execute", "place")
    for desc in (replay_desc, live_desc):
        for mref in desc.method_refs:
            spec = spec_by_ref[(mref.id, mref.version, mref.content_digest)]
            assert spec.read_only is True, f"{desc.source_id} binds a non-read method"
            assert not any(m in mref.id.lower() for m in write_markers)
    # sweep the whole catalog's capabilities: none is an order/signal write capability.
    snap = ch.phase9_catalog_snapshot()
    for entry in snap.capability_manifest:
        low = entry.ref.id.lower()
        assert not any(m in low for m in write_markers), (
            f"a write-shaped capability leaked into the phase9 catalog: {entry.ref.id}"
        )


def test_source_materials_are_the_two_handlers_and_two_descriptors():
    replay_desc, live_desc, materials = ch.build_phase9_source_materials()
    from guanlan_v2.orchestration.catalog import ResolvedTextMaterial

    assert all(isinstance(m, ResolvedTextMaterial) for m in materials)
    kinds = sorted(m.kind for m in materials)
    assert kinds == ["guardrail", "guardrail", "handler", "handler"]
    # each descriptor's handler_ref resolves to a handler material in the set.
    handler_keys = {m.ref_key for m in materials if m.kind == "handler"}
    assert (replay_desc.handler_ref.id, replay_desc.handler_ref.version) in handler_keys
    assert (live_desc.handler_ref.id, live_desc.handler_ref.version) in handler_keys
