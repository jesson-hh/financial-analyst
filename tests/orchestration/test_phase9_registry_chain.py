def test_registry_matches_the_frozen_golden_entry_for_entry():
    assert SCHEMA_GOLDEN.exists(), f"missing golden: {SCHEMA_GOLDEN}"
    doc = _load_json(SCHEMA_GOLDEN)
    assert doc["algorithm"] == CJSON_VERSION == "sha256+cjson-v1"
    assert doc["base_registry_digest"] == p8.PHASE8_REGISTRY_DIGEST
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    reg = ch.build_phase9_registry(ch.PHASE9_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    assert set(manifest) == set(golden), (
        "phase9 registry key set drifted from phase9_schema_manifest_v1.json; "
        "regenerate + re-review by hand if intended"
    )
    for key in sorted(golden):
        assert manifest[key] == golden[key], f"JSON-schema digest drift for {key}"
    assert reg.registry_digest == doc["registry_digest"]


def test_inherited_entries_are_byte_identical_to_the_phase8_golden():
    phase8_doc = _load_json(GOLDEN_DIR / "phase8_schema_manifest_v1.json")
    phase8 = {e["key"]: e["json_schema_digest"] for e in phase8_doc["entries"]}
    reg = ch.build_phase9_registry(ch.PHASE9_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    # every Phase-8 (cumulative) key is inherited byte-identical …
    for key, digest in phase8.items():
        assert manifest[key] == digest, f"inherited schema {key} drifted in phase9"
    # … and the only new keys are exactly the nine Phase-9 public contracts.
    new_keys = set(manifest) - set(phase8)
    assert {k.split("@")[0] for k in new_keys} == EXPECTED_PUBLIC_NAMES
    assert len(new_keys) == 9


