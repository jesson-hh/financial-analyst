def _rotation_draft(nodes, sinks):
    from guanlan_v2.orchestration.spec import PlanDraft
    from guanlan_v2.orchestration.enums import DataMode
    from guanlan_v2.orchestration.presets import PlanSource
    from guanlan_v2.orchestration.refs import PayloadRef

    snap = lc.phase8_catalog_snapshot()
    reg = lc.build_phase8_registry(lc.PHASE8_BASE_REGISTRY_DIGEST)
    ref = PayloadRef(namespace="main", object_id="ctx", content_digest="0" * 64)
    return PlanDraft(
        id="plan.rotation", run_id="run-rot", request_id="req-rot", phase="main",
        source=PlanSource.DYNAMIC, goal="rotation dual-slot", as_of=datetime(2026, 7, 1, tzinfo=timezone.utc),
        mode=DataMode.ONLINE, context_snapshot_ref=ref, nodes=tuple(nodes),
        sink_node_ids=tuple(sinks), catalog_version=snap.catalog_version,
        catalog_digest=snap.catalog_digest, schema_registry_digest=reg.registry_digest,
        budget_request_tokens=1000, budget_request_llm_invocations=2, max_concurrency=2)


