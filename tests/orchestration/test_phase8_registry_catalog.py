def test_resolver_resolves_all_chain_digests_without_reinterpretation():
    from guanlan_v2.orchestration.eventstore import SchemaRegistryResolver
    from guanlan_v2.orchestration.schema_registry import default_registry
    from guanlan_v2.orchestration.runtime_contracts import (
        PHASE2_BASE_REGISTRY_DIGEST,
        phase2_runtime_registry,
    )
    from guanlan_v2.orchestration.data.schema_registry import build_phase3_registry
    from guanlan_v2.orchestration.memory.schema_registry import (
        PHASE3_FULL_BASE_REGISTRY_DIGEST,
        build_phase3_full_registry,
    )

    p1 = default_registry()
    p2 = phase2_runtime_registry(PHASE2_BASE_REGISTRY_DIGEST)
    p3_data = build_phase3_registry(p2.registry_digest)
    p3_full = build_phase3_full_registry(PHASE3_FULL_BASE_REGISTRY_DIGEST)
    p4 = trial.build_phase4_registry(trial.PHASE4_BASE_REGISTRY_DIGEST)
    p5 = bootstrap.build_phase5_registry(bootstrap.PHASE5_BASE_REGISTRY_DIGEST)
    p6 = shadow.build_phase6_registry(shadow.PHASE6_BASE_REGISTRY_DIGEST)
    p7reg = p7.build_phase7_registry(p7.PHASE7_BASE_REGISTRY_DIGEST)
    p8 = lc.build_phase8_registry(lc.PHASE8_BASE_REGISTRY_DIGEST)

    regs = (p1, p2, p3_data, p3_full, p4, p5, p6, p7reg, p8)
    digests = [r.registry_digest for r in regs]
    # all nine chain digests are distinct — no "latest" alias collapsed them.
    assert len(set(digests)) == 9

    resolver = SchemaRegistryResolver()
    for reg in regs:
        resolver.register(reg)
    # a Plan bound to any upstream digest resolves to that exact registry.
    assert resolver.resolve(p7reg.registry_digest) is p7reg
    assert resolver.resolve(p8.registry_digest) is p8
    # a Phase-<=7 Plan never reinterprets to the Phase-8 registry.
    assert resolver.resolve(p1.registry_digest) is not p8
    assert resolver.resolve(p7reg.registry_digest) is not p8


