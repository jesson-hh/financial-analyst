def test_market_rotation_two_distinct_slots_pass_structure_validation():
    from guanlan_v2.orchestration.spec import PlanNode, validate_plan_structure
    # the frozen resolution: two market.rotation instances writing DISTINCT slots — no
    # shared slot, hence no reducer and no single-writer (unreduced_multi_write) violation.
    draft = _rotation_draft(
        [PlanNode(id="rot-mainline", worker_id="market.rotation",
                  writes_slot="slot.mainline_rotation"),
         PlanNode(id="rot-sector", worker_id="market.rotation",
                  writes_slot="slot.sector_rotation")],
        ["rot-mainline", "rot-sector"])
    validate_plan_structure(draft)  # passes — the single-writer rule owns writes_slot


def test_market_rotation_shared_slot_without_reducer_is_rejected():
    from guanlan_v2.orchestration.spec import PlanNode
    # the explicitly-rejected alternative (one slot + a reducer that would FUSE two
