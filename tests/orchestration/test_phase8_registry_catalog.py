    discovered = _discover_phase8_contract_models()
    public = set(lc.PHASE8_PUBLIC_MODELS)
    internal = set(lc.PHASE8_INTERNAL_MODELS)
    classified = public | internal
    assert not (public & internal), "a Phase-8 contract cannot be both registered and internal"
    unclassified = discovered - classified
    assert not unclassified, (
        "unreviewed Phase-8 public contracts: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in unclassified))
    )
    phantom = classified - discovered
    assert not phantom, (
        "classified models not discovered in the nine Phase-8 modules: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in phantom))
    )
    assert classified == discovered
    assert len(public) + len(internal) == len(discovered) == 45


