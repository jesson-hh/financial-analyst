def test_deep_decide_preset_reference_binds_the_committed_sealed_record():
    """The catalog's preset-record reference reproduces from the COMMITTED
    preset file (identity + semantic digest + registered schema key) and the
    golden pins it — a preset edit without a catalog re-freeze is loud."""
    from guanlan_v2.orchestration.pipeline.assembly import (
        PRODUCTION_PRESETS_DIR,
        load_phase10_preset_registry,
    )
    from guanlan_v2.orchestration.pipeline.deep_decide import (
        DEEP_DECIDE_PRESET_ID,
    )

    doc = _load_json(CATALOG_GOLDEN)["deep_decide_preset_record_ref"]
    record = load_phase10_preset_registry(PRODUCTION_PRESETS_DIR).get(
        DEEP_DECIDE_PRESET_ID)
    assert doc == {
        "kind": "plan_preset_record_ref",
        "preset_id": DEEP_DECIDE_PRESET_ID,
        "preset_version": "1",
        "record_digest": record.semantic_digest(),
        "schema_key": PLAN_PRESET_RECORD_V2_SCHEMA_REF.key,
    }
    # a drifted reference doc is refused at build (not just at golden compare).
    _refs, materials = ch.build_phase10_materials()
    from guanlan_v2.orchestration.catalog_runtime import build_text_material

    tampered = []
    for m in materials:
        if m.ref.id == ch.DEEP_DECIDE_PRESET_REF_MATERIAL_ID:
            bad = dict(json.loads(m.raw_utf8.decode("utf-8")))
            bad["record_digest"] = "0" * 64
            _r, mat = build_text_material(
                id=m.ref.id, version="1", kind="guardrail",
                raw=json.dumps(bad, sort_keys=True, ensure_ascii=False,
                               separators=(",", ":")).encode("utf-8"))
            tampered.append(mat)
        else:
            tampered.append(m)
    with pytest.raises(CatalogError, match="preset reference does not match"):
        ch.build_phase10_catalog_snapshot(
            p9.phase9_catalog_snapshot(), resolved_materials=tuple(tampered))


def test_inherited_catalog_manifests_are_byte_identical_to_phase9():
    base = p9.phase9_catalog_snapshot()
    snap = ch.phase10_catalog_snapshot()
    # skills and capabilities pass through byte-identical; workers grow by
    # exactly the three cand.* finals; only the content manifest gains the four
    # Phase-10 materials.
    assert snap.skill_manifest == base.skill_manifest
    assert snap.capability_manifest == base.capability_manifest
    base_workers = {w.id: w for w in base.workers}
    for w in snap.workers:
        if w.id in base_workers:
            assert w == base_workers[w.id], f"inherited worker {w.id} drifted"
    assert {w.id for w in snap.workers} - set(base_workers) == EXPECTED_NEW_WORKER_IDS
    base_content = {e.ref_key: e for e in base.content_manifest}
    for e in snap.content_manifest:
        if e.ref_key in base_content:
            assert e == base_content[e.ref_key], (
                f"inherited content material {e.ref_key} drifted in phase10"
            )
    added = [e for e in snap.content_manifest if e.ref_key not in base_content]
    assert len(added) == 4  # three handlers + one preset-reference guardrail
    for e in added:
        assert e.source_identity == ch.PHASE10_SOURCE_IDENTITY


