def test_internal_map_partitions_the_contract_surface_exactly():
    discovered = _discover_phase10_contract_models()
    public = set(ch.PHASE10_PUBLIC_MODELS)
    internal = set(ch.PHASE10_INTERNAL_MODELS)
    classified = public | internal
    assert not (public & internal), (
        "a Phase-10 contract cannot be both registered and internal"
    )
    unclassified = discovered - classified
    assert not unclassified, (
        "unreviewed Phase-10 public contracts: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in unclassified))
    )
    phantom = classified - discovered
    assert not phantom, (
        "classified contract models not discovered in the Phase-10 modules: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in phantom))
    )
    assert classified == discovered


