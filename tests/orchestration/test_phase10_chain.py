def test_plan_preset_record_v2_registers_as_the_reviewed_base_name_at_v2():
    """Amendment 3: the registered identity is ``PlanPresetRecord@2`` (the exact
    ``assembly.PLAN_PRESET_RECORD_V2_SCHEMA_REF``), served by a 1:1
    field-for-field registration subclass of the reviewed ``PlanPresetRecordV2``
    — same fields, deterministic schema, resolvable through the sealed registry.
    """
    from guanlan_v2.orchestration.digest import content_digest

    assert PLAN_PRESET_RECORD_V2_SCHEMA_REF.key == "PlanPresetRecord@2"
    reg = ch.build_phase10_registry(ch.PHASE10_BASE_REGISTRY_DIGEST)
    resolved = reg.resolve(PLAN_PRESET_RECORD_V2_SCHEMA_REF)
