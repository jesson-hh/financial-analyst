    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    assert golden["PlanPresetRecord@2"] == content_digest(
        resolved.model_json_schema())
    # …and distinct from the inherited v1 family entry.
    assert "PlanPresetRecord@1" in golden
    assert golden["PlanPresetRecord@1"] != golden["PlanPresetRecord@2"]


