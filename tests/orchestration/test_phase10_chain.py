def test_registry_matches_the_frozen_golden_entry_for_entry():
    assert SCHEMA_GOLDEN.exists(), f"missing golden: {SCHEMA_GOLDEN}"
    doc = _load_json(SCHEMA_GOLDEN)
    assert doc["algorithm"] == CJSON_VERSION == "sha256+cjson-v1"
    assert doc["base_registry_digest"] == p9.PHASE9_REGISTRY_DIGEST
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    reg = ch.build_phase10_registry(ch.PHASE10_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    assert set(manifest) == set(golden), (
        "phase10 registry key set drifted from phase10_schema_manifest_v1.json; "
        "regenerate + re-review by hand if intended"
    )
    for key in sorted(golden):
        assert manifest[key] == golden[key], f"JSON-schema digest drift for {key}"
    assert reg.registry_digest == doc["registry_digest"]


def test_inherited_entries_are_byte_identical_to_the_phase9_golden():
    phase9_doc = _load_json(GOLDEN_DIR / "phase9_schema_manifest_v1.json")
    phase9 = {e["key"]: e["json_schema_digest"] for e in phase9_doc["entries"]}
    reg = ch.build_phase10_registry(ch.PHASE10_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    # every Phase-9 (cumulative) key is inherited byte-identical …
    for key, digest in phase9.items():
        assert manifest[key] == digest, f"inherited schema {key} drifted in phase10"
    # … and the only new keys are exactly the six Phase-10 registered keys
    # (five own-name @1 plus PlanPresetRecord@2 — and NEVER PlanPresetRecordV2@2).
    new_keys = set(manifest) - set(phase9)
    assert new_keys == set(EXPECTED_NEW_KEYS)
    assert "PlanPresetRecordV2@2" not in manifest
    assert len(new_keys) == 6


