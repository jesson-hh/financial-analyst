def test_public_and_internal_partition_the_three_module_surface_exactly():
    discovered = _discover_phase5_contract_models()
    public = set(bootstrap.PHASE5_PUBLIC_MODELS)
    internal = set(bootstrap.PHASE5_INTERNAL_MODELS)
    classified = public | internal
    assert not (public & internal), "a Phase-5 contract cannot be both registered and internal"
    unclassified = discovered - classified
    assert not unclassified, (
        "unreviewed Phase-5 public contracts: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in unclassified))
    )
    phantom = classified - discovered
    assert not phantom, (
        "classified models not discovered in the three Phase-5 modules: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in phantom))
    )
    assert classified == discovered
    assert len(public) + len(internal) == len(discovered)


