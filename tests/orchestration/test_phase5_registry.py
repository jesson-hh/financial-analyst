#: the three Phase-5 contract modules the completeness firewall governs.
PHASE5_CONTRACT_MODULES = (
    "guanlan_v2.orchestration.market.factors",
    "guanlan_v2.orchestration.memory.experience",
    "guanlan_v2.orchestration.bootstrap",
)

#: the 17 reviewed names the registered Phase-5 surface must equal.
EXPECTED_PUBLIC_NAMES = frozenset({
    "MarketFactorValue", "MarketFactorSetSpec", "MarketFactorReport",
    "RegimeReport", "RotationReport",
    "RegimeCase", "RealizedRegime", "CaseMatured", "CaseReviewed",
    "RegimeGraderSpec", "ExperienceScalerSnapshot", "ExperienceQuery",
    "ExperienceSelection",
    "ExperiencePrefetchBinding", "BootstrapRuntimeProfile", "BootstrapPlan",
    "BootstrapContextManifest",
})

#: the five Phase-5 payload names whose deferred-absence guards Task 9 flips.
FLIPPED_DEFERRED_NAMES = (
    "MarketFactorValue", "MarketFactorReport", "RegimeReport",
    "RealizedRegime", "RotationReport",
)

#: still-deferred Phase 6/8 payloads — absent from every registry in the chain.
STILL_DEFERRED_NAMES = (
    "TargetPosition", "PortfolioTargetProposal", "TargetPortfolioIntent",
    "DecisionSchedule", "DebateMessage",
)


def _load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _discover_phase5_contract_models() -> set[type]:
    found: set[type] = set()
    for module_name in PHASE5_CONTRACT_MODULES:
        module = importlib.import_module(module_name)
        for obj in vars(module).values():
            if (
                inspect.isclass(obj)
                and issubclass(obj, ContractModel)
                and obj not in (ContractModel, DigestModel)
                and obj.__module__ == module_name
                and not obj.__name__.startswith("_")
            ):
                found.add(obj)
    return found


