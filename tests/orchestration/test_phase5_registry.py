def test_bootstrap_context_manifest_none_ref_requires_badge():
    mf = _typed_ref("MarketFactorReport")
    regime = _typed_ref("RegimeReport")
    rotation = _typed_ref("RotationReport")

    # all three present, no missing badge — accepted.
    ok = bootstrap.BootstrapContextManifest.build(
        context_snapshot_digest="d" * 64,
        bootstrap_plan_digest="e" * 64,
        bootstrap_run_id="run-1",
        market_factor_report_ref=mf,
        regime_report_ref=regime,
        rotation_report_ref=rotation,
    )
    assert ok.content_digest == ok.semantic_digest()

    # regime None without the badge — rejected.
    with pytest.raises(Exception):
        bootstrap.BootstrapContextManifest.build(
            context_snapshot_digest="d" * 64, bootstrap_plan_digest="e" * 64,
            bootstrap_run_id="run-1", market_factor_report_ref=mf,
            regime_report_ref=None, rotation_report_ref=rotation,
        )

    # regime None WITH the badge — accepted; rotation None WITH its badge too.
    honest = bootstrap.BootstrapContextManifest.build(
        context_snapshot_digest="d" * 64, bootstrap_plan_digest="e" * 64,
        bootstrap_run_id="run-1", market_factor_report_ref=mf,
        regime_report_ref=None, rotation_report_ref=None,
        degradation_badges=("regime_missing", "rotation_missing"),
    )
    assert honest.regime_report_ref is None
    assert honest.rotation_report_ref is None


