# Point 2 — golden equality; inherited byte-identical; upstream goldens frozen   #
# =========================================================================== #
def test_registry_matches_the_frozen_golden_entry_for_entry():
    assert SCHEMA_GOLDEN.exists(), f"missing golden: {SCHEMA_GOLDEN}"
    doc = _load_json(SCHEMA_GOLDEN)
    assert doc["algorithm"] == CJSON_VERSION == "sha256+cjson-v1"
    assert doc["base_registry_digest"] == trial.PHASE4_REGISTRY_DIGEST
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    reg = bootstrap.build_phase5_registry(bootstrap.PHASE5_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    assert set(manifest) == set(golden), (
        "phase5 registry key set drifted from phase5_schema_manifest_v1.json; "
        "regenerate + re-review by hand if intended"
    )
    for key in sorted(golden):
        assert manifest[key] == golden[key], f"JSON-schema digest drift for {key}"
    assert reg.registry_digest == doc["registry_digest"]


def test_inherited_entries_are_byte_identical_to_the_phase4_golden():
    phase4_doc = _load_json(GOLDEN_DIR / "phase4_schema_manifest_v1.json")
    phase4 = {e["key"]: e["json_schema_digest"] for e in phase4_doc["entries"]}
    reg = bootstrap.build_phase5_registry(bootstrap.PHASE5_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    # every Phase-4 (cumulative) key is inherited byte-identical …
    for key, digest in phase4.items():
        assert manifest[key] == digest, f"inherited schema {key} drifted in phase5"
    # … and the only new keys are exactly the 17 Phase-5 public contracts.
    new_keys = set(manifest) - set(phase4)
    assert {k.split("@")[0] for k in new_keys} == EXPECTED_PUBLIC_NAMES
    assert len(new_keys) == 17


def test_new_public_contract_digests_are_recomputable_from_the_models():
    doc = _load_json(SCHEMA_GOLDEN)
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    for model in bootstrap.PHASE5_PUBLIC_MODELS:
        key = f"{model.__name__}@{model.model_fields['schema_version'].default}"
        assert golden[key] == content_digest(model.model_json_schema())


def test_upstream_phase1_golden_is_byte_unchanged():
    raw = (GOLDEN_DIR / "schema_manifest_v1.json").read_bytes()
    assert hashlib.sha256(raw).hexdigest() == UPSTREAM_GOLDEN_SHA256[
        "schema_manifest_v1.json"
    ], "Phase 1 golden changed — Phase 5 must never regenerate it"


