def _typed_ref(name: str) -> TypedPayloadRef:
    return TypedPayloadRef(
        schema_ref=SchemaRef(name=name, version="1"),
        payload_ref=PayloadRef(namespace="main", object_id="obj-x", content_digest="a" * 64),
    )


