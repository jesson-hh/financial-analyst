def test_catalog_adds_exactly_four_final_workers():
    base = trial.phase4_catalog_snapshot()
    snap = bootstrap.phase5_catalog_snapshot()
    assert count_final_workers(snap) == count_final_workers(base) + 4
    base_ids = {w.id for w in base.workers}
    added = sorted(w.id for w in snap.workers if w.id not in base_ids)
    assert added == [
        "market.factor", "market.factor_miner", "market.regime", "market.rotation"
    ]
    added_final = sorted(
        w.id for w in snap.workers
        if w.catalog_role == "final" and w.id not in base_ids
    )
    assert added_final == added  # all four additions are finals


def test_compat_workers_and_inherited_entries_pass_through_unchanged():
    base = trial.phase4_catalog_snapshot()
    snap = bootstrap.phase5_catalog_snapshot()
    base_workers = {w.id: w for w in base.workers}
    new_workers = {w.id: w for w in snap.workers}
    # every inherited worker (incl. compat.*) is byte-identical.
    for wid, w in base_workers.items():
        assert new_workers[wid] == w, f"inherited worker {wid} changed in phase5"
    compat = [w.id for w in snap.workers if w.id.startswith("compat.")]
    assert compat == ["compat.news_sentiment", "compat.report_writer"]
    # inherited content/skill/capability entries pass through byte-identical.
    base_content = {e.ref_key: e for e in base.content_manifest}
    new_content = {e.ref_key: e for e in snap.content_manifest}
    for key, e in base_content.items():
        assert new_content[key] == e


def test_factor_miner_placeholder_pins_the_r9_boundary():
    snap = bootstrap.phase5_catalog_snapshot()
    miner = next(w for w in snap.workers if w.id == "market.factor_miner")
    assert miner.catalog_role == "final"
    assert miner.can_emit_decision is False
    assert miner.decision_authority == "none"
