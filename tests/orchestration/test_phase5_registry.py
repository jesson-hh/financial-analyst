"""Phase 5 · Task 9 — cumulative Phase-5 registry / catalog chain + goldens.

Locks the linear registry/catalog chain that later phases consume as their base:

* ``build_phase5_registry(expected_phase4_digest)`` builds a *fresh sealed*
  cumulative registry over the exact Phase-4 cumulative set (Phase-1 public +
  Phase-2 runtime facts + Phase-3 data + Phase-3 memory + the 16
  Evaluator-Optimizer contracts) plus the reviewed :data:`PHASE5_PUBLIC_MODELS`
  (17 registered Bootstrap Lane 0 contracts); a wrong base digest is rejected
  before any registration; inherited entries stay byte-identical to their
  Phase-≤4 goldens; the digest is registration-order independent and matches the
  hand-reviewed golden;
* ``phase5_catalog_snapshot()`` extends *only* the canonical Phase-4 catalog with
  the three Lane 0 finals plus the #25 ``market.factor_miner`` placeholder
  (``count_final_workers`` +4) and the Lane 0 experience capability/bridge + #25
  prompt/skill materials; ``compat.*`` and every inherited entry pass through
  byte-identical; a wrong base is rejected;
* the Phase-5 public/internal partition over the three Phase-5 contract modules
  is exhaustive and disjoint (the completeness-firewall pattern, scoped to
  Phase 5);
* old Plans binding the Phase 1 / Phase 2 / Phase 3 data / Phase 3 full / Phase 4
  digests stay resolvable side-by-side with the Phase 5 digest through the
  ``SchemaRegistryResolver`` — no "latest" alias, no reinterpretation;
* the two bootstrap payload models (``BootstrapPlan`` /
  ``BootstrapContextManifest``) are schema-frozen here so the registry freeze
  covers them (Task 10 builds only the runtime glue on top).

Goldens are NEVER auto-regenerated by tests: a changed manifest is a reviewed
contract change regenerated by hand and re-reviewed.

Run: ``pytest tests/orchestration/test_phase5_registry.py -v``
"""
