def test_joint_gate_material_is_utf8_no_bom():
    raw = JOINT_GATE_MATERIAL_PATH.read_bytes()
    assert not raw.startswith(b"\xef\xbb\xbf"), "joint-gate material must have no BOM"
    raw.decode("utf-8")  # strict UTF-8 parse (raises on failure)
    _ref, material = trial.joint_gate_material()
    assert material.raw_utf8 == raw


def test_one_flipped_material_byte_fails_digest_verification():
    from guanlan_v2.orchestration.catalog import catalog_material_digest
    from guanlan_v2.orchestration.catalog_runtime import build_text_material

    ref, material = trial.joint_gate_material()
    # the honest material self-verifies.
    assert catalog_material_digest(material) == ref.content_digest
    tampered = bytearray(material.raw_utf8)
    tampered[-1] = tampered[-1] ^ 0x01
    _tref, tampered_material = build_text_material(
        id=ref.id, version=ref.version, kind="gate_metric", raw=bytes(tampered)
    )
    assert catalog_material_digest(tampered_material) != ref.content_digest
    assert tampered_material.ref.content_digest != ref.content_digest


