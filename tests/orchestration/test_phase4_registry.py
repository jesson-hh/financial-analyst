def test_state_cell_union_is_the_reviewed_phase3_seven_plus_phase4_four():
    from guanlan_v2.orchestration.trial_ledger import (
        PHASE4_STATE_CELL_NAMESPACES,
        PHASE4_TRIAL_STATE_CELL_NAMESPACES,
    )
    from guanlan_v2.orchestration.memory.models import PHASE3_MEMORY_STATE_CELL_NAMESPACES

    assert len(PHASE3_MEMORY_STATE_CELL_NAMESPACES) == 7
    assert len(PHASE4_TRIAL_STATE_CELL_NAMESPACES) == 4
    expected = tuple(sorted(
        set(PHASE3_MEMORY_STATE_CELL_NAMESPACES) | set(PHASE4_TRIAL_STATE_CELL_NAMESPACES)
    ))
    assert PHASE4_STATE_CELL_NAMESPACES == expected
    assert list(PHASE4_STATE_CELL_NAMESPACES) == sorted(PHASE4_STATE_CELL_NAMESPACES)
    assert len(set(PHASE4_STATE_CELL_NAMESPACES)) == len(PHASE4_STATE_CELL_NAMESPACES)
    assert len(PHASE4_STATE_CELL_NAMESPACES) == 11


