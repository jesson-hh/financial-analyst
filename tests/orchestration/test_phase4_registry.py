def test_build_phase4_registry_rejects_a_wrong_expected_digest():
    with pytest.raises(trial.Phase4RegistryError):
        trial.build_phase4_registry("0" * 64)


def test_build_phase4_registry_seals_and_matches_the_frozen_digest():
    reg = trial.build_phase4_registry(trial.PHASE4_BASE_REGISTRY_DIGEST)
    assert reg.sealed is True
    assert reg.registry_digest == trial.PHASE4_REGISTRY_DIGEST
    # a fresh sealed instance per call (never a shared mutable singleton).
    other = trial.build_phase4_registry(trial.PHASE4_BASE_REGISTRY_DIGEST)
    assert other is not reg
    assert other.registry_digest == reg.registry_digest


def test_phase4_base_registry_digest_is_the_phase3_full_digest():
    assert trial.PHASE4_BASE_REGISTRY_DIGEST == _phase3_full_digest()
    assert trial.PHASE4_REGISTRY_DIGEST != trial.PHASE4_BASE_REGISTRY_DIGEST


# =========================================================================== #
# Point 2 — golden equality; inherited byte-identical; upstream goldens frozen   #
# =========================================================================== #
def test_registry_matches_the_frozen_golden_entry_for_entry():
    assert SCHEMA_GOLDEN.exists(), f"missing golden: {SCHEMA_GOLDEN}"
    doc = _load_json(SCHEMA_GOLDEN)
    assert doc["algorithm"] == CJSON_VERSION == "sha256+cjson-v1"
    assert doc["base_registry_digest"] == _phase3_full_digest()
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    reg = trial.build_phase4_registry(trial.PHASE4_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    assert set(manifest) == set(golden), (
        "phase4 registry key set drifted from phase4_schema_manifest_v1.json; "
        "regenerate + re-review by hand if intended"
    )
    for key in sorted(golden):
        assert manifest[key] == golden[key], f"JSON-schema digest drift for {key}"
    assert reg.registry_digest == doc["registry_digest"]


def test_inherited_entries_are_byte_identical_to_the_phase3_full_golden():
    phase3_doc = _load_json(GOLDEN_DIR / "phase3_full_schema_manifest_v1.json")
    phase3 = {e["key"]: e["json_schema_digest"] for e in phase3_doc["entries"]}
    reg = trial.build_phase4_registry(trial.PHASE4_BASE_REGISTRY_DIGEST)
    manifest = {e.key: e.json_schema_digest for e in reg.manifest()}
    # every Phase-3 full key is inherited byte-identical …
    for key, digest in phase3.items():
        assert manifest[key] == digest, f"inherited schema {key} drifted in phase4"
    # … and the only new keys are exactly the 16 Phase-4 public contracts.
    new_keys = set(manifest) - set(phase3)
    assert {k.split("@")[0] for k in new_keys} == EXPECTED_PUBLIC_NAMES


def test_new_public_contract_digests_are_recomputable_from_the_models():
    doc = _load_json(SCHEMA_GOLDEN)
    golden = {e["key"]: e["json_schema_digest"] for e in doc["entries"]}
    for model in trial.PHASE4_PUBLIC_MODELS:
        key = f"{model.__name__}@{model.model_fields['schema_version'].default}"
        assert golden[key] == content_digest(model.model_json_schema())


def test_upstream_goldens_are_byte_unchanged():
    for name, sha in UPSTREAM_GOLDEN_SHA256.items():
        raw = (GOLDEN_DIR / name).read_bytes()
        assert hashlib.sha256(raw).hexdigest() == sha, (
            f"upstream golden {name} changed — Phase 4 must never regenerate it"
        )


