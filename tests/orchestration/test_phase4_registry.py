# Point 6 — exactly one new gate_metric entry; workers/capabilities unchanged    #
# =========================================================================== #
def test_only_new_entry_is_the_gate_metric_and_manifests_are_otherwise_unchanged():
    from guanlan_v2.orchestration.memory.catalog import phase3_full_catalog_snapshot

    base = phase3_full_catalog_snapshot()
    snap = trial.phase4_catalog_snapshot()

    base_content = {(e.ref.id, e.ref.version): e for e in base.content_manifest}
    new_content = {(e.ref.id, e.ref.version): e for e in snap.content_manifest}
    added = set(new_content) - set(base_content)
    assert added == {("optimize.joint_gate", "1")}
    entry = new_content[("optimize.joint_gate", "1")]
    assert entry.kind == "gate_metric"
    assert entry.ref.id == "optimize.joint_gate"
    assert entry.ref.version == "1"
    # every inherited content entry is preserved byte-identically.
    for key, e in base_content.items():
        assert new_content[key] == e

    # workers + capabilities + skills are unchanged from the Phase-3 full snapshot.
    assert snap.workers == base.workers
    assert snap.capability_manifest == base.capability_manifest
    assert snap.skill_manifest == base.skill_manifest


def test_golden_gate_metric_matches_the_material():
    doc = _load_json(CATALOG_GOLDEN)
