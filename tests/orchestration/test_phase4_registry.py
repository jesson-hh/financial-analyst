"""Phase 4 · Task 9 — cumulative Phase-4 registry / catalog chain + goldens.

Locks the linear registry/catalog chain that Phase 5 consumes as its sole base:

* ``build_phase4_registry(expected_phase3_full_digest)`` builds a *fresh sealed*
  cumulative registry over the exact Phase-3 FULL (data + memory) cumulative set
  plus the reviewed :data:`PHASE4_PUBLIC_MODELS` (16 registered Evaluator-Optimizer
  contracts); a wrong base digest is rejected before any registration; inherited
  entries stay byte-identical to the Phase-3 full golden; the digest is
  registration-order independent and matches the hand-reviewed golden;
* ``build_phase4_catalog_snapshot(...)`` extends *only* the canonical Phase-3 full
  catalog with exactly one ``gate_metric`` content material (``optimize.joint_gate``
  @1) sourced byte-for-byte from
  ``config/orchestration/materials/optimize/joint_gate_v1.md`` (UTF-8, no BOM);
  workers/capabilities are unchanged; a tampered material byte fails the digest;
* the Phase-4 public/internal partition over the six Phase-4 contract modules is
  exhaustive and disjoint (the Phase-1 completeness-firewall pattern, scoped to
  Phase 4);
* old Plans binding the Phase 1 / Phase 2 / Phase 3 data-only / Phase 3 full
  digests stay resolvable side-by-side with the Phase 4 digest through the
  ``SchemaRegistryResolver`` — no "latest" alias, no reinterpretation;
* the sealed startup state-cell union is exactly the reviewed Phase-3 seven plus
  Phase-4 four (lexicographic).

Goldens are NEVER auto-regenerated by tests: a changed manifest is a reviewed
contract change regenerated by hand and re-reviewed.

Run: ``pytest tests/orchestration/test_phase4_registry.py -v``
"""
