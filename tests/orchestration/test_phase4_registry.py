def test_internal_map_is_a_contract_model_reason_map():
    assert isinstance(trial.PHASE4_INTERNAL_MODELS, dict)
    for model, reason in trial.PHASE4_INTERNAL_MODELS.items():
        assert isinstance(model, type) and issubclass(model, ContractModel)
        assert isinstance(reason, str) and reason.strip()
    # the two nested evaluation components deliberately stay unregistered.
    names = {m.__name__ for m in trial.PHASE4_INTERNAL_MODELS}
    assert names == {"GateResult", "HonestyGateReport"}


def test_public_and_internal_partition_the_six_module_surface_exactly():
    discovered = _discover_phase4_contract_models()
    classified = set(trial.PHASE4_PUBLIC_MODELS) | set(trial.PHASE4_INTERNAL_MODELS)
    assert not (set(trial.PHASE4_PUBLIC_MODELS) & set(trial.PHASE4_INTERNAL_MODELS)), (
        "a Phase-4 contract cannot be both registered and internal"
    )
    unclassified = discovered - classified
    assert not unclassified, (
        "unreviewed Phase-4 public contracts: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in unclassified))
    )
    phantom = classified - discovered
    assert not phantom, (
        "classified models not discovered in the six Phase-4 modules: "
        + ", ".join(sorted(f"{m.__module__}.{m.__name__}" for m in phantom))
    )
    assert classified == discovered
    assert len(trial.PHASE4_PUBLIC_MODELS) + len(trial.PHASE4_INTERNAL_MODELS) == len(
        discovered
    )


